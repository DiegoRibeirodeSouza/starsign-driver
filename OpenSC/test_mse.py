from smartcard.System import readers
from smartcard.util import toHexString

def transmit(conn, apdu):
    print(f"> {toHexString(apdu)}")
    data, sw1, sw2 = conn.transmit(apdu)
    print(f"< {toHexString(data)} {sw1:02X} {sw2:02X}")
    return sw1, sw2

r = readers()[0]
conn = r.createConnection()
conn.connect()

print("Opening channel 1...")
transmit(conn, [0x00, 0x70, 0x00, 0x00, 0x01])

print("Selecting PKCS15 AID on channel 1...")
transmit(conn, [0x01, 0xA4, 0x04, 0x00, 0x0C, 0xA0, 0x00, 0x00, 0x00, 0x63, 0x50, 0x4B, 0x43, 0x53, 0x2D, 0x31, 0x35])

print("Trying MSE SET with CLA=01...")
transmit(conn, [0x01, 0x22, 0x41, 0xB6, 0x06, 0x80, 0x01, 0x12, 0x84, 0x01, 0x01])

print("Trying MSE SET with CLA=01 and Key Ref=00...")
transmit(conn, [0x01, 0x22, 0x41, 0xB6, 0x06, 0x80, 0x01, 0x12, 0x84, 0x01, 0x00])

print("Trying MSE SET with CLA=01 and Alg=02...")
transmit(conn, [0x01, 0x22, 0x41, 0xB6, 0x06, 0x80, 0x01, 0x02, 0x84, 0x01, 0x01])

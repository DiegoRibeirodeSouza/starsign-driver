from smartcard.System import readers

r = readers()[0]
conn = r.createConnection()
conn.connect()

def tx(apdu):
    return conn.transmit(apdu)

# Open channel
tx([0x00, 0x70, 0x00, 0x00, 0x01])
# Select PKCS15
tx([0x01, 0xA4, 0x04, 0x00, 0x0C, 0xA0, 0x00, 0x00, 0x00, 0x63, 0x50, 0x4B, 0x43, 0x53, 0x2D, 0x31, 0x35])

found = False
for key_ref in [0x00, 0x01, 0x02, 0x03, 0x10, 0x11, 0x21]:
    for alg_ref in range(0x20):
        apdu = [0x01, 0x22, 0x41, 0xB6, 0x06, 0x80, 0x01, alg_ref, 0x84, 0x01, key_ref]
        data, sw1, sw2 = tx(apdu)
        if sw1 != 0x6A or sw2 != 0x80:
            print(f"Key={key_ref:02X} Alg={alg_ref:02X} -> {sw1:02X} {sw2:02X}")
            found = True

if not found:
    print("All combinations returned 6A 80")
